//! # omnitrade-script
//!
//! Custom strategy DSL interpreter for omnitrade.
//!
//! Provides a domain-specific language for defining trading strategies
//! that execute over historical and live tick/candle buffers:
//! - **Lexer**: Tokenizes strategy source text
//! - **Parser**: Builds an Abstract Syntax Tree (AST) from tokens
//! - **Evaluator**: Executes AST nodes against market data buffers
//!
//! ## Status
//!
//! **Phase 4** — Not yet implemented. This is a placeholder crate.
