//! Paper trading matching engine for simulated order execution.
//!
//! Supports Market, Limit, StopLoss, TakeProfit, and TrailingStop orders.
//! For live trading, wrap with `omnitrade_risk::RiskGuard::check_order()` to enforce
//! position limits and drawdown constraints BEFORE submission.

use omnitrade_core::{Candle, Order, OrderStatus, OrderType, Side, Tick};

use crate::error::EngineError;
use crate::fees::{FeeSchedule, SlippageModel};
use crate::fill::{FillType, OrderFill, OrderFillBuilder};

/// Matching engine that executes market, limit, stop-loss, take-profit, and trailing-stop orders.
#[derive(Debug, Clone)]
pub struct MatchingEngine {
    /// Fee schedule applied to executed trades.
    pub fee_schedule: FeeSchedule,
    /// Slippage model applied to execution prices.
    pub slippage_model: SlippageModel,
    /// Monotonic sequence counter tracking execution fills generated by this engine instance.
    pub next_fill_id: u64,
}

impl MatchingEngine {
    /// Creates a new `MatchingEngine` with the given fee schedule and slippage model.
    pub fn new(fee_schedule: FeeSchedule, slippage_model: SlippageModel) -> Self {
        Self {
            fee_schedule,
            slippage_model,
            next_fill_id: 1,
        }
    }

    /// Validates an incoming order size and price prior to submission.
    ///
    /// # Errors
    /// Returns [`EngineError::InvalidOrderSize`] if `quantity <= 0.0`, `quantity.is_nan()`,
    /// or for limit orders if `price <= 0.0` or `price.is_nan()`.
    pub fn submit_order(&self, order: &Order) -> Result<(), EngineError> {
        if order.quantity <= 0.0 || order.quantity.is_nan() {
            return Err(EngineError::InvalidOrderSize {
                size: order.quantity,
                reason: "order quantity must be positive and non-NaN",
            });
        }

        match &order.order_type {
            OrderType::Limit | OrderType::StopLimit
                if order.price <= 0.0 || order.price.is_nan() =>
            {
                return Err(EngineError::InvalidOrderSize {
                    size: order.price,
                    reason: "limit order price must be positive and non-NaN",
                });
            }
            OrderType::StopMarket if order.stop_price <= 0.0 || order.stop_price.is_nan() => {
                return Err(EngineError::InvalidOrderSize {
                    size: order.stop_price,
                    reason: "stop price must be positive and non-NaN",
                });
            }
            OrderType::StopLoss {
                trigger_price,
                limit_price,
            }
            | OrderType::TakeProfit {
                trigger_price,
                limit_price,
            } => {
                if *trigger_price <= 0.0 || trigger_price.is_nan() {
                    return Err(EngineError::InvalidOrderSize {
                        size: *trigger_price,
                        reason: "trigger price must be positive and non-NaN",
                    });
                }
                if let Some(limit) = limit_price {
                    if *limit <= 0.0 || limit.is_nan() {
                        return Err(EngineError::InvalidOrderSize {
                            size: *limit,
                            reason: "limit price must be positive and non-NaN",
                        });
                    }
                }
            }
            OrderType::TrailingStop { percent } if *percent <= 0.0 || percent.is_nan() => {
                return Err(EngineError::InvalidOrderSize {
                    size: *percent,
                    reason: "trailing stop percent must be positive and non-NaN",
                });
            }
            _ => {}
        }

        Ok(())
    }

    /// Processes an incoming market tick against a list of pending orders.
    ///
    /// Returns a vector of generated [`OrderFill`]s and removes completed orders from `pending_orders`.
    pub fn process_tick(&mut self, tick: &Tick, pending_orders: &mut Vec<Order>) -> Vec<OrderFill> {
        let mut fills = Vec::new();

        for order in pending_orders.iter_mut() {
            let (should_fill, fill_base_price, is_maker, fill_type) =
                self.evaluate_fill_condition(order, tick);

            if !should_fill {
                continue;
            }

            let fill_qty = order.remaining_quantity();
            if fill_qty < f64::EPSILON {
                if order.status != OrderStatus::Filled {
                    order.status = OrderStatus::Filled;
                }
                continue;
            }

            let fill_price = self
                .slippage_model
                .apply_slippage(fill_base_price, order.side);
            let notional = fill_price * fill_qty;
            let fee = self.fee_schedule.compute_fee(notional, is_maker);

            order.filled_quantity += fill_qty;
            order.updated_at_ms = tick.timestamp_ms;
            order.status = if order.remaining_quantity() <= f64::EPSILON {
                OrderStatus::Filled
            } else {
                OrderStatus::PartiallyFilled
            };

            self.next_fill_id += 1;

            let fill_builder = OrderFillBuilder::new()
                .order_id(order.id)
                .symbol(order.symbol.clone())
                .side(order.side)
                .fill_price(fill_price)
                .fill_quantity(fill_qty)
                .fee(fee, self.fee_schedule.fee_asset.clone())
                .timestamp_ms(tick.timestamp_ms)
                .is_maker(is_maker)
                .fill_type(fill_type);

            match fill_builder.build() {
                Ok(fill) => fills.push(fill),
                Err(err) => {
                    tracing::warn!(
                        "Failed to construct OrderFill for order {}: {:?}",
                        order.id,
                        err
                    );
                }
            }
        }

        pending_orders.retain(|order| order.is_active());
        fills
    }

    /// Processes a candle to evaluate SL, TP, and Trailing Stop orders.
    ///
    /// Returns a vector of generated [`OrderFill`]s and removes completed orders from `pending_orders`.
    pub fn process_candle(
        &mut self,
        candle: &Candle,
        pending_orders: &mut Vec<Order>,
    ) -> Vec<OrderFill> {
        let mut fills = Vec::new();

        for order in pending_orders.iter_mut() {
            let (should_fill, fill_base_price, is_maker, fill_type) =
                self.evaluate_candle_fill(order, candle);

            if !should_fill {
                continue;
            }

            let fill_qty = order.remaining_quantity();
            if fill_qty < f64::EPSILON {
                if order.status != OrderStatus::Filled {
                    order.status = OrderStatus::Filled;
                }
                continue;
            }

            let fill_price = self
                .slippage_model
                .apply_slippage(fill_base_price, order.side);
            let notional = fill_price * fill_qty;
            let fee = self.fee_schedule.compute_fee(notional, is_maker);

            order.filled_quantity += fill_qty;
            order.updated_at_ms = candle.timestamp_ms;
            order.status = if order.remaining_quantity() <= f64::EPSILON {
                OrderStatus::Filled
            } else {
                OrderStatus::PartiallyFilled
            };

            self.next_fill_id += 1;

            let fill_builder = OrderFillBuilder::new()
                .order_id(order.id)
                .symbol(order.symbol.clone())
                .side(order.side)
                .fill_price(fill_price)
                .fill_quantity(fill_qty)
                .fee(fee, self.fee_schedule.fee_asset.clone())
                .timestamp_ms(candle.timestamp_ms)
                .is_maker(is_maker)
                .fill_type(fill_type);

            match fill_builder.build() {
                Ok(fill) => fills.push(fill),
                Err(err) => {
                    tracing::warn!(
                        "Failed to construct OrderFill for order {}: {:?}",
                        order.id,
                        err
                    );
                }
            }
        }

        pending_orders.retain(|order| order.is_active());
        fills
    }

    /// Evaluates whether a tick should trigger a fill for an order.
    /// Returns (should_fill, fill_base_price, is_maker, fill_type).
    fn evaluate_fill_condition(&self, order: &Order, tick: &Tick) -> (bool, f64, bool, FillType) {
        match (&order.order_type, order.side) {
            (OrderType::Market, _) => (true, tick.price, false, FillType::Regular),
            (OrderType::Limit, Side::Buy) if tick.price <= order.price => {
                (true, order.price, true, FillType::Regular)
            }
            (OrderType::Limit, Side::Sell) if tick.price >= order.price => {
                (true, order.price, true, FillType::Regular)
            }
            _ => (false, 0.0, false, FillType::Regular),
        }
    }

    /// Evaluates whether a candle should trigger a fill for SL/TP/Trailing orders.
    /// Returns (should_fill, fill_base_price, is_maker, fill_type).
    fn evaluate_candle_fill(
        &self,
        order: &mut Order,
        candle: &Candle,
    ) -> (bool, f64, bool, FillType) {
        match &order.order_type {
            OrderType::StopLoss {
                trigger_price,
                limit_price,
            } => {
                // Sell-SL schützt ein Long (fällt auf Trigger), Buy-SL schützt ein Short (steigt).
                let hit = match order.side {
                    Side::Sell => candle.low <= *trigger_price,
                    Side::Buy => candle.high >= *trigger_price,
                };
                if hit {
                    let fill_price = limit_price.unwrap_or(*trigger_price);
                    // Ohne Limit wird der Stop als Markt-Order ausgeführt: Taker-Gebühr.
                    (true, fill_price, limit_price.is_some(), FillType::StopLoss)
                } else {
                    (false, 0.0, false, FillType::Regular)
                }
            }
            OrderType::TakeProfit {
                trigger_price,
                limit_price,
            } => {
                // Sell-TP schließt ein Long im Plus (steigt), Buy-TP ein Short im Plus (fällt).
                let hit = match order.side {
                    Side::Sell => candle.high >= *trigger_price,
                    Side::Buy => candle.low <= *trigger_price,
                };
                if hit {
                    let fill_price = limit_price.unwrap_or(*trigger_price);
                    (true, fill_price, limit_price.is_some(), FillType::TakeProfit)
                } else {
                    (false, 0.0, false, FillType::Regular)
                }
            }
            OrderType::TrailingStop { percent } => {
                // `trailing_highest_price` hält das laufende Extrem: Hoch bei Sell (Long-Schutz),
                // Tief bei Buy (Short-Schutz).
                match order.side {
                    Side::Sell => {
                        let extreme = order
                            .trailing_highest_price
                            .map_or(candle.high, |h| h.max(candle.high));
                        order.trailing_highest_price = Some(extreme);
                        let threshold = extreme * (1.0 - percent);
                        if candle.low <= threshold {
                            (true, threshold, false, FillType::TrailingStop)
                        } else {
                            (false, 0.0, false, FillType::Regular)
                        }
                    }
                    Side::Buy => {
                        let extreme = order
                            .trailing_highest_price
                            .map_or(candle.low, |l| l.min(candle.low));
                        order.trailing_highest_price = Some(extreme);
                        let threshold = extreme * (1.0 + percent);
                        if candle.high >= threshold {
                            (true, threshold, false, FillType::TrailingStop)
                        } else {
                            (false, 0.0, false, FillType::Regular)
                        }
                    }
                }
            }
            _ => (false, 0.0, false, FillType::Regular),
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use omnitrade_core::TimeInForce;

    fn setup_engine() -> MatchingEngine {
        let fee_schedule =
            FeeSchedule::new(0.001, 0.002, "USDT").expect("fee schedule creation should succeed");
        let slippage_model = SlippageModel::new(10.0).expect("slippage model should succeed");
        MatchingEngine::new(fee_schedule, slippage_model)
    }

    fn create_test_order(
        id: u64,
        side: Side,
        order_type: OrderType,
        price: f64,
        quantity: f64,
    ) -> Order {
        Order {
            id,
            symbol: "BTCUSDT".to_string(),
            side,
            order_type,
            time_in_force: TimeInForce::GTC,
            price,
            stop_price: 0.0,
            quantity,
            filled_quantity: 0.0,
            status: OrderStatus::New,
            created_at_ms: 1000,
            updated_at_ms: 1000,
            trailing_highest_price: None,
        }
    }

    #[test]
    fn market_buy_order_filled_at_tick_price_plus_slippage() {
        let mut engine = setup_engine();
        let order = create_test_order(1, Side::Buy, OrderType::Market, 0.0, 1.0);
        let mut pending = vec![order];
        let tick = Tick::new(2000, 50_000.0, 1.0, false);

        let fills = engine.process_tick(&tick, &mut pending);

        assert_eq!(fills.len(), 1);
        let fill = &fills[0];
        assert!((fill.fill_price - 50_050.0).abs() < 1e-6);
        assert_eq!(fill.fill_quantity, 1.0);
        assert!(!fill.is_maker);
        assert!(pending.is_empty());
    }

    #[test]
    fn stop_loss_triggers_on_candle_low() {
        let mut engine = setup_engine();
        let mut order = create_test_order(
            1,
            Side::Sell,
            OrderType::StopLoss {
                trigger_price: 49_000.0,
                limit_price: None,
            },
            0.0,
            1.0,
        );
        order.trailing_highest_price = None;
        let mut pending = vec![order];

        let candle = Candle::new(2000, 50_000.0, 50_500.0, 48_500.0, 49_500.0, 1000.0);
        let fills = engine.process_candle(&candle, &mut pending);

        assert_eq!(fills.len(), 1);
        assert_eq!(fills[0].fill_type, FillType::StopLoss);
        assert!(pending.is_empty());
    }

    #[test]
    fn take_profit_triggers_on_candle_high() {
        let mut engine = setup_engine();
        let mut order = create_test_order(
            1,
            Side::Buy,
            OrderType::TakeProfit {
                trigger_price: 51_000.0,
                limit_price: None,
            },
            0.0,
            1.0,
        );
        order.trailing_highest_price = None;
        let mut pending = vec![order];

        let candle = Candle::new(2000, 50_000.0, 51_500.0, 49_500.0, 50_500.0, 1000.0);
        let fills = engine.process_candle(&candle, &mut pending);

        assert_eq!(fills.len(), 1);
        assert_eq!(fills[0].fill_type, FillType::TakeProfit);
        assert!(pending.is_empty());
    }

    #[test]
    fn trailing_stop_initializes_highest_on_first_candle() {
        let mut engine = setup_engine();
        let order = create_test_order(
            1,
            Side::Sell,
            OrderType::TrailingStop { percent: 0.05 },
            0.0,
            1.0,
        );
        assert_eq!(order.trailing_highest_price, None);
        let mut pending = vec![order];

        // First candle: highest should be initialized to candle.high
        let candle1 = Candle::new(2000, 50_000.0, 51_000.0, 50_000.0, 50_500.0, 1000.0);
        let fills1 = engine.process_candle(&candle1, &mut pending);
        assert!(fills1.is_empty());
        assert_eq!(pending[0].trailing_highest_price, Some(51_000.0));
    }

    #[test]
    fn trailing_stop_updates_highest_and_triggers() {
        let mut engine = setup_engine();
        let order = create_test_order(
            1,
            Side::Sell,
            OrderType::TrailingStop { percent: 0.05 },
            0.0,
            1.0,
        );
        let mut pending = vec![order];

        // First candle: price goes up, highest = 51_000
        let candle1 = Candle::new(2000, 50_000.0, 51_000.0, 50_000.0, 50_500.0, 1000.0);
        let fills1 = engine.process_candle(&candle1, &mut pending);
        assert!(fills1.is_empty());
        assert_eq!(pending[0].trailing_highest_price, Some(51_000.0));

        // Second candle: price drops 6% below highest (threshold = 51_000 * 0.95 = 48_450)
        let candle2 = Candle::new(3000, 50_500.0, 50_600.0, 48_000.0, 48_100.0, 1000.0);
        let fills2 = engine.process_candle(&candle2, &mut pending);
        assert_eq!(fills2.len(), 1);
        assert_eq!(fills2[0].fill_type, FillType::TrailingStop);
    }

    #[test]
    fn limit_buy_order_triggers_when_tick_price_less_than_or_equal_to_limit() {
        let mut engine = setup_engine();
        let order = create_test_order(3, Side::Buy, OrderType::Limit, 50_000.0, 1.0);
        let mut pending = vec![order];

        let tick_high = Tick::new(2000, 50_100.0, 1.0, false);
        let tick_equal = Tick::new(2001, 50_000.0, 1.0, false);

        let fills_high = engine.process_tick(&tick_high, &mut pending);
        assert!(fills_high.is_empty());
        assert_eq!(pending.len(), 1);

        let fills_equal = engine.process_tick(&tick_equal, &mut pending);
        assert_eq!(fills_equal.len(), 1);
        let fill = &fills_equal[0];
        assert!((fill.fill_price - 50_050.0).abs() < 1e-6);
        assert!(fill.is_maker);
        assert!(pending.is_empty());
    }

    #[test]
    fn zero_remaining_quantity_marks_order_filled() {
        let mut engine = setup_engine();
        let mut order = create_test_order(1, Side::Buy, OrderType::Market, 0.0, 1.0);
        order.filled_quantity = 1.0; // Fully filled
        order.status = OrderStatus::PartiallyFilled;
        let mut pending = vec![order];

        let tick = Tick::new(2000, 50_000.0, 1.0, false);
        let fills = engine.process_tick(&tick, &mut pending);

        // No new fill generated (order already filled)
        assert!(fills.is_empty());
        // Order should have been marked as Filled, but then removed from pending_orders
        // because retain() only keeps active orders (New, PartiallyFilled)
        assert!(
            pending.is_empty(),
            "Filled orders are removed from pending_orders"
        );
    }

    #[test]
    fn zero_quantity_order_rejected() {
        let engine = setup_engine();
        let zero_qty = create_test_order(1, Side::Buy, OrderType::Market, 0.0, 0.0);
        assert!(engine.submit_order(&zero_qty).is_err());
    }

    #[test]
    fn submit_accepts_stop_loss_with_trigger_price_and_zero_stop_price() {
        let engine = setup_engine();
        let order = create_test_order(
            1,
            Side::Sell,
            OrderType::StopLoss {
                trigger_price: 49_000.0,
                limit_price: None,
            },
            0.0,
            1.0,
        );
        assert!(engine.submit_order(&order).is_ok());
    }

    #[test]
    fn submit_rejects_non_positive_or_nan_trigger_price() {
        let engine = setup_engine();
        for trigger in [0.0, -1.0, f64::NAN] {
            let sl = create_test_order(
                1,
                Side::Sell,
                OrderType::StopLoss {
                    trigger_price: trigger,
                    limit_price: None,
                },
                0.0,
                1.0,
            );
            let tp = create_test_order(
                2,
                Side::Sell,
                OrderType::TakeProfit {
                    trigger_price: trigger,
                    limit_price: None,
                },
                0.0,
                1.0,
            );
            assert!(engine.submit_order(&sl).is_err());
            assert!(engine.submit_order(&tp).is_err());
        }
    }

    #[test]
    fn buy_trailing_stop_tracks_low_and_triggers_on_rise() {
        let mut engine = setup_engine();
        let order = create_test_order(
            1,
            Side::Buy,
            OrderType::TrailingStop { percent: 0.05 },
            0.0,
            1.0,
        );
        let mut pending = vec![order];

        // Erste Kerze: Tief 100, Hoch 103 -> Schwelle 105, kein Auslöser.
        let c1 = Candle::new(1000, 102.0, 103.0, 100.0, 101.0, 10.0);
        assert!(engine.process_candle(&c1, &mut pending).is_empty());
        // Zweite Kerze: neues Tief 90 -> Schwelle 94,5; Hoch 94 reicht nicht.
        let c2 = Candle::new(2000, 95.0, 94.0, 90.0, 92.0, 10.0);
        assert!(engine.process_candle(&c2, &mut pending).is_empty());
        // Dritte Kerze: Hoch 95 >= 94,5 -> löst aus.
        let c3 = Candle::new(3000, 92.0, 95.0, 91.0, 94.0, 10.0);
        let fills = engine.process_candle(&c3, &mut pending);
        assert_eq!(fills.len(), 1);
        assert_eq!(fills[0].fill_type, FillType::TrailingStop);
    }

    #[test]
    fn buy_side_stop_loss_and_take_profit_mirror_sell_side() {
        let mut engine = setup_engine();
        let sl = create_test_order(
            1,
            Side::Buy,
            OrderType::StopLoss {
                trigger_price: 105.0,
                limit_price: None,
            },
            0.0,
            1.0,
        );
        let tp = create_test_order(
            2,
            Side::Buy,
            OrderType::TakeProfit {
                trigger_price: 90.0,
                limit_price: None,
            },
            0.0,
            1.0,
        );
        let mut pending = vec![sl, tp];

        // Hoch 106 löst nur den Buy-SL aus, Tief 95 nicht den Buy-TP.
        let c1 = Candle::new(1000, 100.0, 106.0, 95.0, 100.0, 10.0);
        let fills = engine.process_candle(&c1, &mut pending);
        assert_eq!(fills.len(), 1);
        assert_eq!(fills[0].fill_type, FillType::StopLoss);
    }
}
